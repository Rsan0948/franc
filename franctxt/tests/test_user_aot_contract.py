"""Guard the initial Franc-authored CPL3 code emitter's restricted ABI.

The QEMU roadmap test runs the real Franc-generated bytes separately. These
guards do not claim that compiled user programs have been scheduled yet.
"""
from pathlib import Path
import re
import unittest

ROOT = Path(__file__).resolve().parents[2]


class UserSourceEmitterContract(unittest.TestCase):
    def test_bounded_native_compiler_uses_only_predeclared_registers(self):
        text = (ROOT / "lib/user_aot.frac").read_text()
        registry = (ROOT / "stage4/apps/registry.frac").read_text()
        for word in ("user-code-base", "user-emit-byte", "user-emit-u32",
                     "user-emit-fault", "user-emit-loop", "user-parse",
                     "user-compile"):
            self.assertIn("def " + word + " ", text)
        regs = set(re.findall(r"(?<![a-z0-9-]):([a-z][a-z0-9-]*)", text))
        for name in regs - {"s2p"}:
            self.assertIn(":" + name, registry, name)
        self.assertIn("ide-buffer 3072 +", text)
        self.assertNotIn("ide-buffer 4096 +", text)
        self.assertIn("user-code-base ide-i + ide-n b!", text)

    def test_native_dictionary_capacity_covers_wave3_bundle(self):
        native = (ROOT / "stage4/runtime.S").read_text()
        layout = (ROOT / "stage4/interrupts.S").read_text()
        self.assertIn("cmpq $S2_DICT_ENTRIES,%r9", native)
        self.assertIn(".set S2_DICT_ENTRIES,4096", layout)
        source_paths = [
            line for line in (ROOT / "stage4/app_sources.list").read_text().splitlines()
            if line and not line.startswith("#")
        ]
        source_definitions = sum(
            len([line for line in (ROOT / source).read_text().splitlines()
                 if line.startswith("def ")])
            for source in source_paths
        )
        self.assertLess(source_definitions, 4096,
                        "Native JIT names table cannot hold the app bundle")

    def test_whitelisted_source_and_encoded_machine_code_contract(self):
        text = (ROOT / "lib/user_aot.frac").read_text()
        self.assertIn('s2-next "def" s2-eq', text)
        self.assertIn('s2-next "main" s2-eq', text)
        self.assertIn('s2-next "count" s2-eq', text)
        self.assertIn('ide-source "fault" s2-eq', text)
        self.assertIn('ide-source "again" s2-eq', text)
        self.assertIn('72 user-emit-byte 191 user-emit-byte', text)
        self.assertIn("243 user-emit-byte 144 user-emit-byte", text)
        self.assertIn("15 user-emit-byte 182 user-emit-byte", text)
        # No bytes are executed at ring 0 by the emitter itself.
        self.assertNotIn("s2-run", text)
        self.assertNotIn("user-preempt-probe", text)

    def test_actual_qemu_generation_is_required(self):
        suite = (ROOT / "stage4/qemu_roadmap.py").read_text()
        self.assertIn('"def main 100 count fault ;" user-compile .', suite)
        self.assertIn('"def main 2 count again ;" user-compile .', suite)


if __name__ == "__main__":
    unittest.main()

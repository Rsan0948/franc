#!/usr/bin/env python3
"""Generate compile-time C text for FracOS's ROM-resident library bootstrap."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
LIBS=['fixpt','cf','approx','iv','trans','graphics','ford','spiro','calc','edit','walk','dd']
lines=['/* Generated by stage1/embed_libraries.py; do not hand-edit. */', '#ifndef FRANC_LIBRARY_BUNDLE_H', '#define FRANC_LIBRARY_BUNDLE_H', 'static const char franc_library_source[] =']
for lib in LIBS:
    data=(ROOT/'lib'/f'{lib}.frac').read_text()
    for part in data.splitlines(keepends=True):
        lines.append('  '+json.dumps(part, ensure_ascii=True))
lines+=['  "";', '#endif', '']
output=ROOT/'stage1'/'library_bundle.h'
output.write_text('\n'.join(lines))
print(f'Generated {output}: {output.stat().st_size} bytes')
